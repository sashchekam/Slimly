/// Страница в оттенках серого: байт на пиксель, строки сверху вниз.
///
/// Промежуточная форма между CoreImage и однобитным растром PDF. Порог
/// смотрит на соседей пикселя, а соседей в графе фильтров нет — их видно
/// только в развёрнутом буфере.
struct GrayscaleBuffer: Sendable {
    let width: Int
    let height: Int
    /// Длина ровно `width * height` — выравнивания строк здесь нет.
    let samples: [UInt8]
}
