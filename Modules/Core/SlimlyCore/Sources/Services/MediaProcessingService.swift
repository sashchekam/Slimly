import Foundation

/// Обработка файлов и собственная база сделанного.
///
/// База своя, потому что iOS не помнит, что мы делали с файлами: всё,
/// что показано в профиле, приложение записало о себе само.
public protocol MediaProcessingService: Sendable {
    func stats() async -> ProcessingStats

    /// Журнал работ с датами — из него собирается разрез по инструментам
    /// и по времени. Общая сумма на такой вопрос не отвечает: в ней нет
    /// ни дат, ни того, каким инструментом это сделано.
    func history() async -> ProcessingHistory

    /// Поток событий обработки. Отмена потока останавливает работу —
    /// как и уход из приложения: фоновой обработки здесь нет.
    ///
    /// Готовые файлы остаются внутри приложения: наружу — в медиатеку
    /// или «Файлы» — их выносит только ``save(_:)``.
    func process(_ request: ProcessingRequest) -> AsyncStream<ProcessingEvent>

    /// Разложить готовые файлы по месту.
    ///
    /// Отдельный шаг, а не хвост обработки: пока человек не нажал «сохранить»,
    /// класть что-то в его медиатеку рано.
    ///
    /// Возвращает тот же итог с новыми ссылками: файл, уехавший в «Файлы»,
    /// лежит уже не там, где его записали. Файл, который сохранить
    /// не удалось, переезжает в список отказов — как и при обработке,
    /// один отказ не отменяет остальные.
    func save(_ outcome: ProcessingOutcome) async -> ProcessingOutcome

    /// Дать готовому файлу другое имя — до того, как он ушёл наружу.
    ///
    /// Имя видно в списке итога и в системной шторке шаринга, и под ним же
    /// файл ложится в «Файлы». После сохранения править его поздно: копия
    /// уже разложена по месту, и правка её не догонит.
    ///
    /// Возвращает тот же результат с новым именем и новой ссылкой: имя —
    /// часть пути, и старый адрес после переезда никуда не ведёт.
    func rename(_ result: ProcessingResult, to name: String) async throws -> ProcessingResult
}
