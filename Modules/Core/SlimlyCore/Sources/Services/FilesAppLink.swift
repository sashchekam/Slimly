import Foundation

/// Ссылка, которая открывает системные «Файлы» на нужном файле.
///
/// Сохранить файл мало — его ещё нужно найти: путь «Файлы → На iPhone →
/// Slimly» человек проходит глазами, и подписи под списком для этого мало.
/// Знание о том, как позвать «Файлы», держится здесь одно на приложение,
/// поэтому экранам про особенности системной схемы знать нечего.
public protocol FilesAppLinking: Sendable {
    /// Адрес, по которому система откроет «Файлы» на папке с этим файлом.
    /// `nil` — вести некуда: файла по ссылке уже нет или это вообще не файл
    /// на диске.
    func url(for file: URL) -> URL?
}

/// Ссылка через `shareddocuments://` — единственный способ открыть «Файлы»
/// сразу на нужной папке: своей документированной схемы у них нет.
///
/// Отсюда правило для всего, что на этой ссылке стоит: она необязательная.
/// Схема системная, но не обещанная, и если однажды система перестанет её
/// принимать, пропасть должна кнопка, а не сохранение файла.
///
/// Папка приложения при этом обязана быть видна в «Файлах» — за это отвечают
/// `UIFileSharingEnabled` и `LSSupportsOpeningDocumentsInPlace` в Info.plist:
/// без них ссылка ведёт в пустоту.
public struct FilesAppLink: FilesAppLinking {
    private static let scheme = "shareddocuments://"

    public init() { }

    public func url(for file: URL) -> URL? {
        guard file.isFileURL, FileManager.default.fileExists(atPath: file.path) else { return nil }

        // Ведём на папку, а не на сам файл: адрес файла система понимает как
        // «покажи страницу», и вместо списка сохранённого человек получает
        // превью поверх «Файлов». Файлов за один заход бывает несколько,
        // и показывать нужно их все.
        //
        // Имена приложение даёт с пробелами, а пробел обрывает адрес
        // на середине — путь едет экранированным.
        let folder = file.deletingLastPathComponent()
        return URL(string: Self.scheme + folder.path(percentEncoded: true))
    }
}
