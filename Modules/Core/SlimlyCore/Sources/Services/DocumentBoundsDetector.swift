import Foundation

/// Поиск листа в готовом снимке.
///
/// Отдельно от обработки: экран правки границ показывает рамку до того, как
/// что-то запущено, и просить ради этого собрать документ было бы странно.
/// Работает с данными кадра, а не с ассетом медиатеки, — искать границы нужно
/// ровно в том изображении, которое человек видит на экране: иначе рамка
/// пообещает одно, а обрежется другое.
public protocol DocumentBoundsDetector: Sendable {
    /// Границы листа в долях кадра от левого верхнего угла.
    /// `nil` — листа в кадре не видно, и предлагать нечего.
    func bounds(in imageData: Data) async -> DocumentQuad?
}
