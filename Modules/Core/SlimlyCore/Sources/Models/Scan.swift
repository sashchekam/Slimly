import Foundation

/// Как обрабатываем страницу перед сборкой в PDF.
///
/// Это не «фильтр для красоты»: от режима зависит и читаемость текста,
/// и вес готового документа. Скан договора и скан чека с печатью — разные
/// задачи, и одним режимом их не закрыть.
public enum ScanMode: String, Sendable, Hashable, CaseIterable, Identifiable {
    /// Цвет сохраняем — нужен печатям, подписям и иллюстрациям.
    case color
    /// Оттенки серого: текст читается так же, вес вдвое меньше.
    case grayscale
    /// Чистая двухцветная страница — самый лёгкий и самый контрастный вариант.
    case blackAndWhite

    public var id: String { rawValue }

    /// Подпись в списке форматов. Короткая: «PDF» повторяется во всех трёх
    /// вариантах, и длинные хвосты превратили бы выбор в стену текста.
    public var displayName: String {
        switch self {
        case .color: "цвет"
        case .grayscale: "серый"
        case .blackAndWhite: "ч/б"
        }
    }

    /// Доля исходного веса, которая останется у страницы в PDF.
    ///
    /// Снимок страницы — это 3–5 МБ на двенадцати мегапикселях, а страница
    /// скана — сотни килобайт: кадр уменьшается до печатного разрешения,
    /// а фон становится ровно белым и почти ничего не стоит. Двухцветная
    /// страница выпадает из этого ряда на порядок — она хранится не
    /// картинкой, а битовой маской.
    public var estimatedRatio: Double {
        switch self {
        case .color: 0.14
        case .grayscale: 0.07
        case .blackAndWhite: 0.02
        }
    }
}
