import SlimlyNavigation

/// Отладочное меню — единственный экран, до которого нельзя дойти из
/// интерфейса. Маршрут в роутер кладут только тряска устройства и пять
/// нажатий на строку версии, и только в отладочной сборке: в релизной
/// резолвер не регистрируется и вести сюда нечему.
public enum DebugRoute: Route {
    case menu
    /// Значения удалённого конфига и локальные подмены к ним.
    case remoteConfig
    /// Одно значение целиком: в конфиге лежат объекты JSON, а их не
    /// прочитать и не поправить ни в строке списка, ни в поле алерта.
    case remoteConfigValue(name: String)
    /// Журнал отправленной аналитики: события, их параметры и свойства.
    case analytics
}
